import pandas as pd

def generate_dataset_infographic_card(
    dataset_name: str,
    total_rows: int,
    total_cols: int,
    quality_score: float,
    recommended_task: str,
    top_insight: str
) -> bytes:
    """
    Unit IV Generative Feature:
    Synthesizes a visual illustrative dataset infographic card.
    Uses Pillow with gradient rendering, typography, and visual layout.
    """
    width, height = 900, 520
    img = Image.new("RGB", (width, height), color="#0F172A")
    draw = ImageDraw.Draw(img)

    # 1. Background Gradient Effect
    for y in range(height):
        # Interpolate between deep slate and rich indigo
        r = int(15 + (y / height) * (30 - 15))
        g = int(23 + (y / height) * (41 - 23))
        b = int(42 + (y / height) * (89 - 42))
        draw.line([(0, y), (width, y)], fill=(r, g, b))

    # 2. Decorative Ambient Circles
    draw.ellipse([width - 180, -60, width + 100, 220], fill=(79, 70, 229, 40))
    draw.ellipse([-80, height - 160, 200, height + 120], fill=(16, 185, 129, 30))

    # 3. Header Card
    draw.rectangle([40, 35, width - 40, 110], fill=(30, 41, 59), outline=(99, 102, 241), width=2)
    draw.text((60, 50), "CSV INSIGHT AI – DATASET INTELLIGENCE CARD", fill="#A5B4FC")
    draw.text((60, 75), f"Dataset: {dataset_name[:40]} | Academic Subject: Generative AI", fill="#E2E8F0")

    # 4. Metric Containers
    # Container 1: Rows & Cols
    draw.rectangle([40, 130, 290, 250], fill=(30, 41, 59), outline=(51, 65, 85))
    draw.text((60, 145), "DATASET DIMENSIONS", fill="#94A3B8")
    draw.text((60, 175), f"{total_rows:,} Rows", fill="#F8FAFC")
    draw.text((60, 210), f"{total_cols} Attributes", fill="#38BDF8")

    # Container 2: Health Score
    draw.rectangle([310, 130, 580, 250], fill=(30, 41, 59), outline=(51, 65, 85))
    draw.text((330, 145), "DATA QUALITY HEALTH", fill="#94A3B8")
    draw.text((330, 175), f"{quality_score} / 100", fill="#10B981" if quality_score >= 75 else "#F59E0B")
    draw.text((330, 210), "Deterministic Formula Evaluated", fill="#94A3B8")

    # Container 3: Recommended Task
    draw.rectangle([600, 130, width - 40, 250], fill=(30, 41, 59), outline=(51, 65, 85))
    draw.text((620, 145), "RECOMMENDED ML TASK", fill="#94A3B8")
    draw.text((620, 175), recommended_task[:20], fill="#818CF8")
    draw.text((620, 210), "Algorithmic Match Grounded", fill="#94A3B8")

    # 5. Executive Insight Box
    draw.rectangle([40, 275, width - 40, 440], fill=(15, 23, 42), outline=(99, 102, 241), width=1)
    draw.text((60, 295), "SYNTHESIZED DATASET INTELLIGENCE SUMMARY", fill="#A5B4FC")
    
    # Word-wrap insight
    words = top_insight.split()
    line_buf = ""
    y_text = 330
    for w in words:
        if len(line_buf) + len(w) + 1 <= 80:
            line_buf += (" " if line_buf else "") + w
        else:
            draw.text((60, y_text), line_buf, fill="#CBD5E1")
            y_text += 25
            line_buf = w
            if y_text > 405:
                break
    if line_buf and y_text <= 405:
        draw.text((60, y_text), line_buf, fill="#CBD5E1")

    # Footer
    draw.text((40, 465), "Generated by CSV INSIGHT AI (Student: Atharva Shelar, Roll No: 10, P10)", fill="#64748B")
    draw.text((width - 240, 465), "Unit IV Generative Asset", fill="#64748B")

    # Save to buffer
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    image_bytes = buf.getvalue()
    buf.close()
    return image_bytes

